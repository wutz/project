package v1alpha1

import (
	"k8s.io/apimachinery/pkg/api/resource"
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
	"k8s.io/apimachinery/pkg/runtime"
)

// InstanceTypeGPU describes the GPUs of an instance type.
type InstanceTypeGPU struct {
	// class is the normalised GPU product, e.g. rtx-5090. It is also the
	// Kueue ResourceFlavor name.
	Class string `json:"class"`
	// product is the nvidia.com/gpu.product node label value.
	Product string `json:"product"`
	// count is the number of GPUs per worker.
	Count int32 `json:"count"`
	// memoryMiB is the memory of one GPU.
	// +optional
	MemoryMiB int64 `json:"memoryMiB,omitempty"`
}

// InstanceTypeSpec is computed by the operator from the GPU nodes; it is not
// meant to be edited.
type InstanceTypeSpec struct {
	GPU InstanceTypeGPU `json:"gpu"`
	// cpu and memory per worker: the per-GPU slice of the smallest node in
	// the class (allocatable minus the platform reservation) times gpu.count.
	CPU    resource.Quantity `json:"cpu"`
	Memory resource.Quantity `json:"memory"`
	// nodeSelector places workers on nodes of this class.
	NodeSelector map[string]string `json:"nodeSelector"`
}

// NodeAvailability is the capacity of one node for an instance type.
type NodeAvailability struct {
	Node  string `json:"node"`
	Total int32  `json:"total"`
	Free  int32  `json:"free"`
}

// InstanceTypeStatus reports how many instances fit on the cluster.
type InstanceTypeStatus struct {
	// total is how many instances fit on schedulable nodes when empty.
	Total int32 `json:"total"`
	// free is how many instances fit right now.
	Free int32 `json:"free"`
	// +optional
	Nodes []NodeAvailability `json:"nodes,omitempty"`
	// +optional
	UpdateTime *metav1.Time `json:"updateTime,omitempty"`
}

// +kubebuilder:object:root=true
// +kubebuilder:subresource:status
// +kubebuilder:resource:scope=Cluster,shortName=fit,categories=project
// +kubebuilder:printcolumn:name="GPU",type=string,JSONPath=`.spec.gpu.product`
// +kubebuilder:printcolumn:name="GPUs",type=integer,JSONPath=`.spec.gpu.count`
// +kubebuilder:printcolumn:name="CPU",type=string,JSONPath=`.spec.cpu`
// +kubebuilder:printcolumn:name="Memory",type=string,JSONPath=`.spec.memory`
// +kubebuilder:printcolumn:name="Free",type=integer,JSONPath=`.status.free`
// +kubebuilder:printcolumn:name="Total",type=integer,JSONPath=`.status.total`

// InstanceType is a GPU instance size, generated by the operator from the
// GPU nodes of the cluster.
type InstanceType struct {
	metav1.TypeMeta `json:",inline"`

	// metadata is a standard object metadata
	// +optional
	metav1.ObjectMeta `json:"metadata,omitzero"`

	// spec defines the desired state of InstanceType
	// +required
	Spec InstanceTypeSpec `json:"spec"`

	// status defines the observed state of InstanceType
	// +optional
	Status InstanceTypeStatus `json:"status,omitzero"`
}

// +kubebuilder:object:root=true

// InstanceTypeList contains a list of InstanceType
type InstanceTypeList struct {
	metav1.TypeMeta `json:",inline"`
	metav1.ListMeta `json:"metadata,omitzero"`
	Items           []InstanceType `json:"items"`
}

func init() {
	SchemeBuilder.Register(func(s *runtime.Scheme) error {
		s.AddKnownTypes(SchemeGroupVersion, &InstanceType{}, &InstanceTypeList{})
		return nil
	})
}
